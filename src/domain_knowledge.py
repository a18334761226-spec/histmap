def is_valid_zhou(z: str) -> bool:
    """判断是否为合法的州名。"""
    if not z or len(z) > 3:
        return False
    if z in ZHOU_BLACKLIST or z in NON_ZHOU:
        return False
    if any(ch in ZHOU_BLACKLIST for ch in z):
        return False
    return True


def resolve_col(name: str, norm2col: dict):
    """把史料中的藩镇名解析到方镇表槽位。"""
    if not name:
        return None
    if name in FANZHEN_ALIAS:
        return FANZHEN_ALIAS[name]
    for k, v in FANZHEN_ALIAS.items():
        if k and (name.startswith(k) or k.startswith(name)):
            return v
    return norm2col.get(name)
