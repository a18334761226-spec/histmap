def emit(batch_filter=None):
    pts = []
    for region, rows in BATCHES.items():
        if batch_filter and region != batch_filter:
            continue
        for name, lon, lat, modern in rows:
            simp = to_simplified(name)
            pts.append({"name": simp,                    # 简体：显示与匹配用
                        "name_trad": to_traditional(simp),  # 繁体：与史源对照
                        "lon": lon, "lat": lat,
                        "modern": modern, "region": region,
                        "source": "reconstructed"})
    doc = {
        "_source": ("坐标按《新唐书·地理志》州县沿革对照今地名重建，"
                    "并用 geoBoundaries CHN ADM2（PDDL 公有领域）逐点校验。"
                    "**这是 AI 重建 + 几何验证的数据，不是权威测绘数据。**"),
        "_precision": "约 0.05°（≈5 km）",
        "_license": "数据库权利放弃（与项目一致）；引用时请注明重建方法",
        "batches": list(BATCHES),
        "points": pts,
    }
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    json.dump(doc, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(f"已写出 {len(pts)} 条 -> {OUT}")
    return docs(pts)


def docs(pts):
    return pts


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--batch", default=None, help="只输出某一批（道名）")
    args = ap.parse_args()
    pts = emit(args.batch)
    print(f"批次: {list(BATCHES)}")
    for r, rows in BATCHES.items():
        print(f"  {r}: {len(rows)} 州")


if __name__ == "__main__":
    main()
